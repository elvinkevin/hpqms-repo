from pathlib import Path
import json

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import Response
from fastapi.staticfiles import StaticFiles
from app.core.config import settings
from app.api.router import api_router
from app.api.routes.display import websocket_router

app = FastAPI(
    title="Hospital Queue Management API",
    version="1.0.0",
)

# Configure CORS for local dev and LAN access
app.add_middleware(
    CORSMiddleware,
    allow_origin_regex=settings.CORS_ORIGIN_REGEX,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

frontend_dir = Path(__file__).resolve().parent.parent.parent / "frontend"


@app.get("/static/kiosk-config.js", include_in_schema=False)
async def kiosk_config_js() -> Response:
    """
    Inject the kiosk API key into the kiosk page at serve time.

    The key lives only in server-side configuration (env / .env),
    never in committed frontend JavaScript.
    """
    from app.core.config import settings

    api_key = settings.KIOSK_INTERNAL_API_KEY

    js = (
        "// Generated by the backend — do not edit.\n"
        f'window.__KIOSK_CONFIG__ = {{ apiKey: {json.dumps(api_key)} }};\n'
    )

    return Response(
        content=js,
        media_type="application/javascript",
        headers={"Cache-Control": "no-store"},
    )


app.mount(
    "/static",
    StaticFiles(directory=str(frontend_dir), html=True),
    name="frontend",
)

app.include_router(api_router)
app.include_router(websocket_router)


@app.get("/health", include_in_schema=False)
async def health():
    return {"status": "ok"}


@app.get("/")
async def root():
    return {"message": "Hospital Queue Management API"}